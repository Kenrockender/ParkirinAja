export type TKey = keyof typeof dict.id;

interface I18nCtx {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (k: TKey, params?: Record<string, string | number>) => string;
}

const Ctx = createContext<I18nCtx | null>(null);

// localStorage-backed language store via useSyncExternalStore (SSR-safe, no effect-setState)
const LANG_EVENT = "pb_lang_change";
function subscribe(cb: () => void) {
  window.addEventListener("storage", cb);
  window.addEventListener(LANG_EVENT, cb);
  return () => {
    window.removeEventListener("storage", cb);
    window.removeEventListener(LANG_EVENT, cb);
  };
}
function getSnapshot(): Lang {
  const v = localStorage.getItem("pb_lang");
  return v === "en" ? "en" : "id";
}
function getServerSnapshot(): Lang {
  return "id";
}

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const lang = useSyncExternalStore(subscribe, getSnapshot, getServerSnapshot);

  const setLang = useCallback((l: Lang) => {
    try {
      localStorage.setItem("pb_lang", l);
    } catch {}
    window.dispatchEvent(new Event(LANG_EVENT));
  }, []);

  const t = useCallback(
    (k: TKey, params?: Record<string, string | number>) => {
      let s: string = dict[lang][k] ?? String(k);
      if (params) {
        for (const [key, v] of Object.entries(params)) s = s.split(`{${key}}`).join(String(v));
      }
      return s;
    },
    [lang]
  );

  return <Ctx.Provider value={{ lang, setLang, t }}>{children}</Ctx.Provider>;
}

export function useI18n(): I18nCtx {
  const ctx = useContext(Ctx);
  if (!ctx) throw new Error("useI18n must be used inside I18nProvider");
  return ctx;
}
